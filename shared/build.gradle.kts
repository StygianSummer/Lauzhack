// ---------------------------------------------------------------------------------------------
// tea.BuildInfo: short git sha (shown in the DebugFooter) and the debug flag. `-Prelease=true`
// turns DEBUG off (demo aids hidden). Rewritten only when the content changes.
// ---------------------------------------------------------------------------------------------
val buildInfoDir = layout.buildDirectory.dir("generated/buildinfo/kotlin")
val teaRelease = providers.gradleProperty("release").orElse("false")
val gitShaOutput = providers.exec {
    commandLine("git", "rev-parse", "--short", "HEAD")
    isIgnoreExitValue = true
}.standardOutput.asText
val generateBuildInfo = tasks.register("generateBuildInfo") {
    val out = buildInfoDir
    val release = teaRelease
    val sha = gitShaOutput
    outputs.dir(out)
    outputs.upToDateWhen { false }
    doLast {
        val shaText = runCatching { sha.get().trim() }.getOrDefault("").ifEmpty { "dev" }
        val debug = release.get() != "true"
        val file = out.get().file("tea/BuildInfo.kt").asFile
        val text = "package tea\n\n/** Generated by :shared:generateBuildInfo. */\nobject BuildInfo {\n" +
            "    const val SHA: String = \"$shaText\"\n    const val DEBUG: Boolean = $debug\n}\n"
        file.parentFile.mkdirs()
        if (!file.exists() || file.readText() != text) file.writeText(text)
    }
}

